export const contactCopy = (locale: string): ContactCopy =>
  locale === 'ta' ? contactCopyTamil : locale === 'sa' ? contactCopySanskrit : contactCopyEnglish;

/** Google Forms needs exactly the English option values, regardless of the display language. */
export function contactPurposeOptions(locale: string, values: readonly ContactPurpose[]) {
  return values.map((value, index) => ({ value, label: contactCopy(locale).purposeOptions[index] ?? value }));
}
